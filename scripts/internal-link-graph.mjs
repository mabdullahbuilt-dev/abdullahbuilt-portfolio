// Internal link graph for the 27 canonical routes, from server-rendered HTML.
// Usage: node scripts/internal-link-graph.mjs --base-url http://127.0.0.1:3100 [--out docs/seo/internal-link-graph.md]
import { writeFileSync } from "node:fs";
const args = Object.fromEntries(process.argv.slice(2).map((v, i, a) => v.startsWith("--") ? [v.slice(2), a[i + 1]] : null).filter(Boolean));
const base = String(args["base-url"] || "http://127.0.0.1:3100").replace(/\/$/, "");
const out = args.out || "docs/seo/internal-link-graph.md";
const routes = ["/", "/services/", "/services/custom-software-development/", "/services/saas-development/", "/services/web-application-development/", "/services/api-integration-development/", "/services/business-automation/", "/services/mvp-product-development/", "/services/ai-application-development/", "/services/product-rescue/", "/work/", "/work/resolve/", "/work/meridian/", "/work/repodiet/", "/work/agora-forge/", "/guides/", "/guides/hire-saas-developer/", "/guides/hire-web-app-developer/", "/guides/startup-mvp-development/", "/guides/custom-software-vs-saas/", "/guides/saas-mvp-development-cost/", "/guides/api-integration-planning/", "/guides/rescue-ai-built-web-app/", "/guides/ai-feature-vs-automation/", "/guides/reliable-webhook-integration/", "/about/", "/contact/"];
const strip = html => html.replace(/<script[\s\S]*?<\/script>/g, "");
const text = s => s.replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&").replace(/&#x27;|&#39;/g, "'").replace(/\s+/g, " ").trim();
const graph = {};
for (const route of routes) {
  const html = strip(await (await fetch(base + route)).text());
  // Body links only: skip the shared header and footer navigation so contextual links are visible.
  const main = (html.match(/<main[\s\S]*?<\/main>/) || [html])[0];
  const all = [...html.matchAll(/<a[^>]+href="(\/[^"#?]*)(?:\?[^"]*)?"[^>]*>([\s\S]*?)<\/a>/g)].map(m => ({ href: m[1], anchor: text(m[2]) }));
  const body = [...main.matchAll(/<a[^>]+href="(\/[^"#?]*)(?:\?[^"]*)?"[^>]*>([\s\S]*?)<\/a>/g)].map(m => ({ href: m[1], anchor: text(m[2]) })).filter(l => routes.includes(l.href) && l.href !== route);
  graph[route] = { all: [...new Set(all.map(l => l.href).filter(h => routes.includes(h) && h !== route))], body };
}
// Click depth from the homepage over all links (navigation included).
const depth = { "/": 0 }; let frontier = ["/"];
while (frontier.length) { const next = []; for (const r of frontier) for (const h of graph[r].all) if (depth[h] === undefined) { depth[h] = depth[r] + 1; next.push(h); } frontier = next; }
const inbound = Object.fromEntries(routes.map(r => [r, new Set()])), bodyInbound = Object.fromEntries(routes.map(r => [r, new Set()]));
for (const [from, g] of Object.entries(graph)) { for (const h of g.all) inbound[h].add(from); for (const l of g.body) bodyInbound[l.href].add(from); }
const anchorsTo = Object.fromEntries(routes.map(r => [r, new Map()]));
for (const g of Object.values(graph)) for (const l of g.body) { const m = anchorsTo[l.href]; m.set(l.anchor, (m.get(l.anchor) || 0) + 1); }
const rows = routes.map(r => {
  const anchors = [...anchorsTo[r].entries()].sort((a, b) => b[1] - a[1]);
  const top = anchors.slice(0, 3).map(([a, n]) => `${a.slice(0, 48)} (${n})`).join("; ") || "—";
  const repeat = anchors.length && anchors[0][1] / [...anchorsTo[r].values()].reduce((s, n) => s + n, 0);
  return `| \`${r}\` | ${depth[r] ?? "unreachable"} | ${inbound[r].size} | ${bodyInbound[r].size} | ${new Set(graph[r].body.map(l => l.href)).size} | ${inbound[r].size === 0 ? "**ORPHAN**" : "no"} | ${repeat > 0.6 && anchors.length > 1 ? "high" : "ok"} | ${top.replace(/\|/g, "/")} |`;
});
const lines = [
  "# Internal link graph — 27 canonical routes",
  "",
  `Generated by \`scripts/internal-link-graph.mjs\` against \`${base}\` on ${new Date().toISOString().slice(0, 10)} from server-rendered HTML.`,
  "",
  "Columns:",
  "- **Depth**: clicks from the homepage, including header and footer navigation.",
  "- **Inbound (all)**: distinct pages linking in, navigation included.",
  "- **Inbound (body)**: distinct pages linking in from main content only.",
  "- **Outbound (body)**: distinct canonical pages linked from main content.",
  "- **Anchor concentration**: \"high\" when one anchor text is over 60% of body links to the page.",
  "- **Top body anchors**: the most-used anchor texts, with counts.",
  "",
  "| Route | Depth | Inbound (all) | Inbound (body) | Outbound (body) | Orphan | Anchor concentration | Top body anchors |",
  "|---|---|---|---|---|---|---|---|",
  ...rows,
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(JSON.stringify({ out, orphans: routes.filter(r => inbound[r].size === 0), maxDepth: Math.max(...Object.values(depth)), unreachable: routes.filter(r => depth[r] === undefined) }));
